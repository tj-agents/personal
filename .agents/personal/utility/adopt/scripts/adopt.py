"""Select and deliver mandatory policy for an explicitly adopted personal project."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess
import sys

IDENTITY = "personal@tj-agents"
START = "<!-- BEGIN personal:current-solution"
END = "<!-- END personal:current-solution -->"
BLOCK = re.compile(r"<!-- BEGIN personal:current-solution sha256:[0-9a-f]{64} -->.*?<!-- END personal:current-solution -->", re.DOTALL)
POLICY = Path(__file__).resolve().parents[3] / "policy/current-solution/SKILL.md"
BARE_IMPORT = re.compile(r"^@\S+$")
CI_CALLER = ".github/workflows/check-personal-policy.yml"
CI_CALLER_MARKER = "# Generated by personal:adopt; do not edit.\n"


def fragment() -> str:
    source = POLICY.read_text(encoding="utf-8").replace("\r\n", "\n")
    if not source.startswith("---\n"):
        raise ValueError("policy is missing frontmatter")
    body = source.split("\n---\n", 1)[1].strip()
    if not body:
        raise ValueError("policy body is empty")
    digest = hashlib.sha256(source.encode("utf-8")).hexdigest()
    return f"{START} sha256:{digest} -->\n{body}\n{END}"


def text(path: Path) -> str:
    if path.is_symlink() or (hasattr(path, "is_junction") and path.is_junction()):
        raise ValueError(f"refusing linked instruction file: {path}")
    return path.read_text(encoding="utf-8") if path.exists() else ""


def projected(existing: str, block: str) -> str:
    count = policy_block_count(existing)
    if count:
        return BLOCK.sub(lambda _: block, existing)
    return existing.rstrip() + ("\n\n" if existing.strip() else "") + block + "\n"


def policy_block_count(existing: str) -> int:
    count = len(BLOCK.findall(existing))
    if existing.count(START) != count or existing.count(END) != count or count > 1:
        raise ValueError("personal policy has duplicate or malformed block markers")
    return count


def self_import(stripped: str) -> bool:
    if not stripped.startswith("@"):
        return False
    target = stripped[1:]
    if target.startswith("./"):
        target = target[2:]
    return target == "AGENTS.md"


def claude_instructions(existing: str) -> str:
    policy_block_count(existing)
    remaining = BLOCK.sub("", existing)
    lines: list[str] = []
    fence = None
    for line in remaining.splitlines():
        stripped = line.strip()
        if stripped.startswith(("```", "~~~")):
            marker = stripped[0]
            fence = None if fence == marker else marker if fence is None else fence
        elif fence is None and self_import(stripped):
            continue
        elif fence is None and BARE_IMPORT.fullmatch(stripped):
            raise ValueError(f"CLAUDE.md imports {stripped[1:]}; inline it before adopting personal")
        lines.append(line)
    return "\n".join(lines).strip()


def native_plan(root: Path) -> dict[Path, str]:
    # Git for Windows can materialize tracked symlinks as ordinary target-text files.
    if (root / ".git").exists():
        result = subprocess.run(["git", "-C", str(root), "ls-files", "--stage", "-z", "--",
                                 "AGENTS.md", "CLAUDE.md"], capture_output=True, text=True)
        if result.returncode:
            raise ValueError("cannot inspect tracked native instruction file modes")
        if any(entry.startswith("120000 ") for entry in result.stdout.split("\0")):
            raise ValueError("refusing tracked instruction link; replace it with a regular native import before adopting")
    block = fragment()
    agents, claude = root / "AGENTS.md", root / "CLAUDE.md"
    agents_text, claude_text = text(agents), text(claude)
    if claude.exists() and imports_agents(claude_text) and (START in claude_text or END in claude_text):
        raise ValueError("CLAUDE.md imports AGENTS.md and also contains a duplicate personal block")
    merged = claude_instructions(claude_text) if claude.exists() else ""
    combined = agents_text
    if merged and merged not in agents_text:
        combined = agents_text.rstrip() + ("\n\n" if agents_text.strip() else "") + merged
    targets = {agents: projected(combined, block), claude: "@AGENTS.md\n"}

    return targets


def imports_agents(body: str) -> bool:
    fence = None
    for line in body.splitlines():
        stripped = line.strip()
        if stripped.startswith(("```", "~~~")):
            marker = stripped[0]
            fence = None if fence == marker else marker if fence is None else fence
        elif fence is None and self_import(stripped):
            return True
    return False


def ci_caller_removal(root: Path) -> Path | None:
    path = root / CI_CALLER
    if not path.exists():
        return None
    try:
        path.resolve(strict=True).relative_to(root.resolve(strict=True))
    except (OSError, ValueError) as error:
        raise ValueError(
            f"{CI_CALLER}: refusing workflow linked outside the selected root"
        ) from error
    current = text(path)
    if not current.startswith(CI_CALLER_MARKER):
        raise ValueError(f"{CI_CALLER}: refusing to remove unrelated workflow; delete the generated personal:adopt CI caller manually")
    return path


def check_retained_aliases(root: Path) -> None:
    path = root / ".agents/plugins/payloads.json"
    if not path.is_file():
        return
    declaration = json.loads(path.read_text(encoding="utf-8"))
    for field in ("compatibilityAliases", "compatibilitySkillAliases"):
        aliases = declaration.get(field, {})
        if aliases and (not isinstance(aliases, dict) or any(aliases.values())):
            raise ValueError(f"{path}: remove retained {field} and migrate known callers before adopting personal")


def selected(root: Path) -> bool:
    path = root / ".agents/plugins.json"
    if not path.is_file():
        return False
    try:
        selection = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as error:
        raise ValueError("invalid personal plugin selection") from error
    plugins = selection.get("plugins") if isinstance(selection, dict) else None
    marketplaces = (
        selection.get("marketplaces") if isinstance(selection, dict) else None
    )
    marketplace = (
        marketplaces.get("tj-agents") if isinstance(marketplaces, dict) else None
    )
    if (
        not isinstance(selection, dict)
        or type(selection.get("schema_version")) is not int
        or not isinstance(plugins, list)
        or any(not isinstance(plugin, str) for plugin in plugins)
        or not isinstance(marketplaces, dict)
        or any(
            not isinstance(name, str) or not isinstance(details, dict)
            for name, details in marketplaces.items()
        )
        or (marketplace is not None and not isinstance(marketplace, dict))
        or (
            isinstance(marketplace, dict)
            and not isinstance(marketplace.get("repository"), str)
        )
    ):
        raise ValueError("invalid personal plugin selection")
    return (
        selection["schema_version"] == 1
        and IDENTITY in plugins
        and marketplace is not None
        and marketplace["repository"] == "tj-agents/marketplace"
    )


def run(root: Path, mode: str, selection_tool: Path | None) -> int:
    root = root.resolve(strict=True)
    if not root.is_dir():
        raise ValueError("project root must be a directory")
    check_retained_aliases(root)
    is_selected = selected(root)
    targets = native_plan(root)  # validate every native target before asking Core to write
    retiring = ci_caller_removal(root)
    if selection_tool is not None:
        result = subprocess.run([sys.executable, "-B", str(selection_tool), "--root", str(root),
                                 "--plugin", "personal", "--mode", mode], check=False)
        if result.returncode:
            return result.returncode
    elif not is_selected:
        raise ValueError("select personal@tj-agents through the shipped machine plugin-selection tool first, or pass --selection-tool")
    if mode != "preview" and not selected(root):
        raise ValueError("Core selection did not declare personal@tj-agents from tj-agents/marketplace")
    changed = {path: value for path, value in targets.items() if text(path) != value}
    retired = [retiring] if retiring is not None else []
    if mode == "write":
        for path, value in changed.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(value, encoding="utf-8", newline="\n")
        for path in retired:
            path.unlink()
    for path in changed:
        print(f"{mode}: {path.relative_to(root).as_posix()}")
    for path in retired:
        print(f"{mode}: remove {path.relative_to(root).as_posix()}")
    return int(mode == "check" and bool(changed or retired))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, required=True)
    parser.add_argument("--mode", choices=("preview", "write", "check"), required=True)
    parser.add_argument("--selection-tool", type=Path)
    args = parser.parse_args()
    try:
        return run(args.root, args.mode, args.selection_tool)
    except (OSError, ValueError, IndexError, TypeError, AttributeError) as error:
        print(f"Personal adoption failed: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
